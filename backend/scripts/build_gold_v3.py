def sentences(text: str) -> list[str]:
    return [item.strip() for item in re.findall(r"[^.!?]+[.!?]", text)]


def fact(predicate: str, quote: str, **bindings: list[str]) -> dict:
    return {"predicate": predicate, "quote": quote, "bindings": bindings}


def build_document(document: dict) -> dict:
    cfg = CONFIG[document["id"]]
    source = sentences(document["text"])
    owner, owned = cfg["owner"]
    part_subject, *parts = cfg["parts"]
    facts = [
        fact("IS-A", source[0], SUBJECT=[cfg["isa"][0]], OBJECT=[cfg["isa"][1]]),
        fact("LOCATED_AT", source[1], SUBJECT=[cfg["located"][0]], LOCATION=list(cfg["located"][1:])),
        fact("HAS", source[2], SUBJECT=[owner], OBJECT=[owned]),
        *(fact("HAS", source[2], SUBJECT=[part_subject], OBJECT=[part]) for part in parts),
        *(fact("HAS_STATE", source[3], SUBJECT=[cfg["property_subject"]], STATE=[value]) for value in cfg["properties"]),
        fact("CAUSE", source[4], SUBJECT=[cfg["cause"][0]], OBJECT=[cfg["cause"][1]], **cfg["cause_extra"]),
        *(fact("USES_TOOL", source[7], SUBJECT=[cfg["actor"]], TOOL=[tool]) for tool in cfg["tools"]),
        fact("HAS_STATE", source[9], SUBJECT=[cfg["final"][0]], STATE=[cfg["final"][1]], TIME=[cfg["final"][2]]),
    ]
    return {"id": document["id"], "facts": facts}


def trace_chains() -> list[dict]:
    result = []
    depths = (1, 2, 3, 4, 6)
    for document_id, cfg in CONFIG.items():
        for suffix, nodes, links in (
            ("events", cfg["events"], ("CAUSE", "CAUSE", "FOLLOW", "CAUSE", "FOLLOW", "FOLLOW")),
            ("hierarchy", cfg["classes"], ("IS-A",) * 6),
        ):
            result.append({
                "id": f"{document_id}-{suffix}",
                "nodes": nodes,
                "link_types": links,
                "questions": [
                    {
                        "depth": depth,
                        "question": f"Какой узел достигается из «{nodes[0]}» через {depth} рёбер?",
                        "expected_answer": nodes[depth],
                    }
                    for depth in depths
                ],
            })
    return result


def main() -> None:
    corpus = json.loads(CORPUS.read_text(encoding="utf-8"))
    payload = {
        "schema": "ah-memoryhub-gold-v3",
        "description": "Large internal benchmark: exhaustive supported relations in seven labelled sentences per document, plus 100 independent trace questions.",
        "required_trace_questions": 100,
        "documents": [build_document(document) for document in corpus["documents"]],
        "trace_benchmark": trace_chains(),
    }
    OUTPUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    facts = sum(len(document["facts"]) for document in payload["documents"])
    roles = sum(len(values) for document in payload["documents"] for item in document["facts"] for values in item["bindings"].values())
    questions = sum(len(chain["questions"]) for chain in payload["trace_benchmark"])
    print(f"{OUTPUT}: {len(payload['documents'])} documents, {facts} facts, {roles} role assignments, {questions} trace questions")


if __name__ == "__main__":
    main()
